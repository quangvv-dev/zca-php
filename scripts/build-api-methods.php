<?php
/**
 * Generates src/ApiMethods.php (IDE helper, port of scripts/buildAPI.js):
 * one `@method` line per API class in src/Apis.
 *
 * php scripts/build-api-methods.php
 */

require __DIR__ . "/../vendor/autoload.php";

$ignore = ["BaseApi", "Login", "LoginQR", "Listener"];
$files = glob(__DIR__ . "/../src/Apis/*.php");
sort($files, SORT_STRING);

$typeToString = function (?ReflectionType $type): string {
    if ($type === null) return "mixed";
    $str = (string) $type;

    return preg_replace_callback('/[A-Za-z_\\\\]+/', function ($m) {
        $name = $m[0];
        if (in_array(strtolower($name), ["string", "int", "float", "bool", "array", "mixed", "void", "null", "callable", "object", "iterable", "static", "self", "false", "true"], true)) return $name;

        return "\\" . ltrim($name, "\\");
    }, $str);
};

$lines = [];
foreach ($files as $file) {
    $class = "Zca\\Apis\\" . basename($file, ".php");
    if (in_array(basename($file, ".php"), $ignore, true)) continue;
    $ref = new ReflectionClass($class);
    if ($ref->isAbstract() || !$ref->hasMethod("__invoke")) continue;

    $method = $ref->getMethod("__invoke");
    $params = [];
    foreach ($method->getParameters() as $p) {
        $s = $typeToString($p->getType()) . " " . ($p->isVariadic() ? "..." : "") . "$" . $p->getName();
        if ($p->isDefaultValueAvailable()) {
            $s .= " = " . ($p->isDefaultValueConstant() ? "\\" . $p->getDefaultValueConstantName() : var_export($p->getDefaultValue(), true));
        }
        $params[] = str_replace(["NULL", "array (\n)"], ["null", "[]"], $s);
    }
    $name = lcfirst($ref->getShortName());
    $lines[] = " * @method " . $typeToString($method->getReturnType()) . " {$name}(" . implode(", ", $params) . ") see {@see \\{$class}}";
}

$content = "<?php\n\nnamespace Zca;\n\n/**\n * IDE helper generated by scripts/build-api-methods.php, do not edit.\n *\n" . implode("\n", $lines) . "\n */\ninterface ApiMethods\n{\n}\n";
file_put_contents(__DIR__ . "/../src/ApiMethods.php", $content);
echo count($lines) . " methods written\n";
